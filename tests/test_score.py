"""Checks that hold whatever rules Gary picks. Run: python -m pytest -q"""

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import score  # noqa: E402

EMPTY_ITEM = {"id": "x", "link": {"url": "https://example.org/x"}}


def test_every_rule_returns_bool_on_empty_item():
    # Rules must not crash on missing fields; that's most of the real-world bugs.
    for name, letter, rule in score.RULES:
        assert isinstance(rule(EMPTY_ITEM), bool), name
        assert letter in "FAIR", name


def test_empty_item_scores_zero():
    assert score.score_item(EMPTY_ITEM)["score"] == 0


def test_score_is_a_fraction():
    s = score.score_item({"title": "Water use in Kansas"})["score"]
    assert 0 <= s <= 1


def test_rules_cover_more_than_one_letter():
    assert len({letter for _, letter, _ in score.RULES}) >= 2


@pytest.mark.skipif(not score.load_items(), reason="no harvested data; run scripts/harvest.py")
def test_no_rule_is_constant_on_real_data():
    # A rule every item passes (or fails) can't tell items apart. Fields like `id`
    # and `link` are generated by ScienceBase, so they're always present.
    items = score.load_items()
    for name, _, rule in score.RULES:
        passed = sum(rule(i) for i in items)
        assert 0 < passed < len(items), f"{name} passes {passed}/{len(items)} items"
